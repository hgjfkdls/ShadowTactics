import { readdirSync, writeFileSync, existsSync } from 'fs';
import { join, parse } from 'path';

const TEXTURES_DIR = 'public/models/textures';
const OUTPUT_FILE = 'src/client/board/availableTextures.ts';

function main() {
  if (!existsSync(TEXTURES_DIR)) {
    console.log(`Directory ${TEXTURES_DIR} not found, generating empty list.`);
    writeGenerated([]);
    return;
  }

  const files = readdirSync(TEXTURES_DIR).filter(f => /\.(png|jpg|jpeg|webp)$/i.test(f));
  const textures = [];

  for (const file of files) {
    const name = parse(file).name.toLowerCase();

    // Detect type by suffix: grass_albedo, grass_normal, grass_height
    let terrain = name;
    let channel = 'albedo';
    for (const suffix of ['_albedo', '_normal', '_roughness', '_ao']) {
      if (name.endsWith(suffix)) {
        terrain = name.slice(0, -suffix.length);
        channel = suffix.slice(1);
        break;
      }
    }

    textures.push({
      terrain,
      channel,
      path: `/models/textures/${file}`,
    });
  }

  // Group by terrain for easy lookup
  const grouped = {};
  for (const t of textures) {
    if (!grouped[t.terrain]) grouped[t.terrain] = {};
    grouped[t.terrain][t.channel] = t.path;
  }

  writeGenerated(textures, grouped);
  const terrains = Object.keys(grouped);
  console.log(`Scanned ${files.length} texture files for ${terrains.length} terrains: ${terrains.join(', ')}`);
}

function writeGenerated(textures, grouped) {
  const content = `// Auto-generated by scripts/generate-textures.mjs
// Do not edit manually. Run: node scripts/generate-textures.mjs

export type TextureFiles = {
  albedo?: string;
  normal?: string;
  roughness?: string;
  ao?: string;
};

export const AVAILABLE_TEXTURES: Record<string, TextureFiles> = ${JSON.stringify(grouped, null, 2)};
`;

  writeFileSync(OUTPUT_FILE, content, 'utf-8');
}

main();
