import { readdirSync, writeFileSync, existsSync } from 'fs';
import { join, parse } from 'path';

const DECORATIONS_DIR = 'public/models/decorations';
const OUTPUT_FILE = 'src/client/board/availableDecorations.ts';

function main() {
  if (!existsSync(DECORATIONS_DIR)) {
    console.log(`Directory ${DECORATIONS_DIR} not found, creating empty list.`);
    writeGenerated([]);
    return;
  }

  const files = readdirSync(DECORATIONS_DIR).filter(f => f.endsWith('.glb'));
  const decorations = files.map(f => {
    const name = parse(f).name;
    return {
      id: name,
      name: name.charAt(0).toUpperCase() + name.slice(1).replace(/_/g, ' '),
      path: `/models/decorations/${f}`,
      scale: 1.0,
    };
  });

  writeGenerated(decorations);
  console.log(`Generated ${decorations.length} decorations: ${decorations.map(d => d.id).join(', ')}`);
}

function writeGenerated(decorations) {
  const content = `// Auto-generated by scripts/generate-decorations.mjs
// Do not edit manually. Run: node scripts/generate-decorations.mjs

export type GeneratedDecoration = {
  id: string;
  name: string;
  path: string;
  scale: number;
};

export const AVAILABLE_DECORATIONS: GeneratedDecoration[] = ${JSON.stringify(decorations, null, 2)};
`;

  writeFileSync(OUTPUT_FILE, content, 'utf-8');
}

main();
